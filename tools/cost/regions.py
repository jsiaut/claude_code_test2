"""v4, point 5 (docs/V4_COST.md, 3.2) : relevé des régions, délimitées à la lecture des copies bench/<langage>_cv.

LANGS[langage] = {
  "dir": répertoire de la copie,
  "files": {fichier: empreinte git (git hash-object) ; tools/cost/count.py refuse de compter si un fichier a changé},
  "regions": {nom: [(fichier, première ligne, dernière ligne), …]} (bornes comprises, lignes numérotées à partir de 1),
  "forms": {"noyau|variante|paramètre": (fonction d'entrée, [régions])},
}
Une région contient ce que la forme ajoute au harnais (3.2) : fonctions appelées dans la zone chronométrée et celles
qu'elles appellent dans le fichier, types et constantes propres à la forme, préparation propre (réserve de fils,
tampons, conversion des données). Le harnais commun (mesure du temps, chargement, somme de contrôle, choix de la
variante) n'en fait pas partie. Une région partagée par plusieurs formes compte dans chacune.
Règle de lecture appliquée à tous les langages : dans le choix de la variante, la ligne qui ne fait qu'appeler la
fonction d'entrée de la forme appartient au harnais ; les lignes qui préparent un état propre à la forme, lancent ou
réveillent des fils, ou combinent leurs résultats, appartiennent à la forme. Les lignes qui mesurent le temps, celles qui
calculent la somme de contrôle et celles qui libèrent la mémoire après la mesure n'appartiennent à aucune forme.
Les directives d'import et d'inclusion n'appartiennent à aucune forme ; les déclarations que le programme écrit lui-même
pour une forme (intrinsèques importés par importc en Nim, extern en Chapel, pragma Import en Ada ; alias de types
vectoriels ; pragmas qui coupent les vérifications autour d'une forme) appartiennent aux formes qui les emploient."""


def _r(f, *spans):
    """Intervalles d'un fichier : _r("ms.c", "138-143", "203") -> [("ms.c", 138, 143), ("ms.c", 203, 203)]."""
    out = []
    for s in spans:
        a, _, b = str(s).partition("-")
        out.append((f, int(a), int(b or a)))
    return out


def _f(entry, *regions):
    return (entry, list(regions))


